  let language = window.atticusLanguage || 'en', mode, observer;
  const originals = new WeakMap();
  const attributes = ['title', 'placeholder', 'aria-label', 'alt'];
  // Personal content is not interface copy, even when it matches a map entry.
  const skip = 'script,style,[contenteditable],#asklist,#dictationhistory,#dictationwords,#profileCategories,#profileSources,#rules,#skills,#routines,#meetinglist,#meetingtitle,#meetingsummary,#meetingactions,#meetingnotes,#meetinganswers,#meetingtranscript,#feedbackbody';
  const labels = '#mode,#fold,#dictwave,#lock,#pointbar > .chip > span,#pointbar .rm,#pointbar img,#ask,#models,#model,#point,#mic';
  const translate = text => maps[language]?.[text] ?? text;
  function value(node, key, current) {
    let saved = originals.get(node);
    if (!saved) { saved = {}; originals.set(node, saved); }
    if (!saved[key] || saved[key].result !== current) saved[key] = { source: current };
    const source = saved[key].source, trimmed = source.trim();
    const result = source.replace(trimmed, translate(trimmed));
    saved[key].result = result;
    return result;
  }
  function element(el) {
    if (el.closest(skip)) return;
    for (const key of attributes) if (el.hasAttribute(key)) {
      const before = el.getAttribute(key), after = value(el, key, before);
      if (after !== before) el.setAttribute(key, after);
    }
    if (el.matches('textarea')) return;
    for (const node of el.childNodes) if (node.nodeType === Node.TEXT_NODE) {
      const after = value(node, 'text', node.nodeValue);
      if (after !== node.nodeValue) node.nodeValue = after;
    }
  }
  function refresh() {
    observer?.disconnect();
    document.documentElement.lang = language;
    if (mode === 'page') document.querySelectorAll('body,body *').forEach(element);
    else if (mode === 'labels') document.querySelectorAll(labels).forEach(element);
    // The overlay is never walked or observed: its thread contains user and model text.
    if (mode === 'page') observer.observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: attributes });
  }
  window.i18n = {
    refresh,
    setLanguage(value) {
      if (value === 'auto') value = window.atticusAutoLanguage || navigator.language.split(/[-_]/)[0];
      language = maps[value] ? value : 'en'; refresh();
    },
    start(value) { observer?.disconnect(); mode = value; observer = new MutationObserver(refresh); refresh(); }
  };
